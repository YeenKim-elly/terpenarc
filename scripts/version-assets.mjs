import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const walk = directory => fs.readdirSync(path.join(root, directory), {withFileTypes: true})
  .flatMap(entry => entry.isDirectory() ? walk(directory + '/' + entry.name) : [directory + '/' + entry.name]);
const generated = 'src/lib/asset-version.js';
const files = ['src', 'styles', 'assets'].flatMap(walk).filter(file => file !== generated).sort();
const hash = createHash('sha256');
for (const file of files) {
  hash.update(file + '\0');
  hash.update(/\.(js|css|svg|json)$/.test(file) ? read(file) : fs.readFileSync(path.join(root, file)));
}
const version = hash.digest('hex').slice(0, 12);
const helper = `// Generated by scripts/version-assets.mjs.\nexport const releaseVersion = '${version}';\nexport const assetURL = path => path + (path.includes('?') ? '&' : '?') + 'v=' + releaseVersion;\n`;
// Mapping every module prevents cached nested imports from surviving a release.
const modules = [...files.filter(file => file.endsWith('.js')), generated].sort();
const imports = Object.fromEntries(modules.map(file => ['./' + file, './' + file + '?v=' + version]));
const map = '  <script type="importmap" id="asset-imports">' + JSON.stringify({imports}) + '</script>\n';
let html = read('index.html').replace(/  <script type="importmap" id="asset-imports">.*?<\/script>\n/g, '');
html = html.replace(/((?:href|src)="(?:styles\/[^"?]+\.css|assets\/[^"?]+\.svg|src\/app\.js))(?:\?v=[^" ]+)?"/g, '$1?v=' + version + '"');
html = html.replace('</head>', map + '</head>');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(path.join(root, generated)) || read(generated) !== helper || read('index.html') !== html) {
    console.error('Asset versions are stale. Run npm run prepare:assets.');
    process.exit(1);
  }
} else {
  fs.writeFileSync(path.join(root, generated), helper);
  fs.writeFileSync(path.join(root, 'index.html'), html);
}
console.log('Asset release: ' + version);
